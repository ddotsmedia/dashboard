'use client';

import { useState } from 'react';
import { X, Lightbulb } from 'lucide-react';

export interface Insight {
  id: string;
  icon: React.ReactNode;
  title: string;
  description: string;
  category: string;
  confidence: number;
  timestamp: Date;
  action?: {
    label: string;
    onClick: () => void;
  };
}

interface AIInsightsWidgetProps {
  insight: Insight;
  onDismiss: (id: string) => void;
}

export function AIInsightsWidget({ insight, onDismiss }: AIInsightsWidgetProps) {
  const [showDetails, setShowDetails] = useState(false);

  const confidenceColor =
    insight.confidence >= 80
      ? 'text-green-600 dark:text-green-400'
      : insight.confidence >= 60
        ? 'text-yellow-600 dark:text-yellow-400'
        : 'text-orange-600 dark:text-orange-400';

  const confidenceBgColor =
    insight.confidence >= 80
      ? 'bg-green-50 dark:bg-green-900/20'
      : insight.confidence >= 60
        ? 'bg-yellow-50 dark:bg-yellow-900/20'
        : 'bg-orange-50 dark:bg-orange-900/20';

  return (
    <div
      className={`p-4 border border-gray-200 dark:border-gray-700 rounded-lg transition-all hover:shadow-md dark:hover:shadow-lg animate-in fade-in slide-in-from-top-2 ${confidenceBgColor}`}
    >
      <div className="flex items-start gap-3">
        {/* Icon */}
        <div className="mt-1 text-blue-600 dark:text-blue-400">
          {insight.icon || <Lightbulb className="w-5 h-5" />}
        </div>

        {/* Content */}
        <div className="flex-1 min-w-0">
          <div className="flex items-start justify-between gap-2">
            <div className="flex-1">
              <h3 className="font-semibold text-sm text-gray-900 dark:text-white mb-1">
                {insight.title}
              </h3>
              <p className="text-xs text-gray-600 dark:text-gray-400 line-clamp-2">
                {insight.description}
              </p>
            </div>
            <button
              onClick={() => onDismiss(insight.id)}
              className="p-1 hover:bg-gray-200 dark:hover:bg-gray-600 rounded transition-colors flex-shrink-0"
            >
              <X className="w-4 h-4 text-gray-500 dark:text-gray-400" />
            </button>
          </div>

          {/* Meta Information */}
          <div className="flex items-center gap-2 mt-3 flex-wrap">
            <span className="inline-flex items-center px-2 py-1 rounded text-xs font-medium bg-white dark:bg-gray-800 text-gray-700 dark:text-gray-300">
              {insight.category}
            </span>
            <span className={`text-xs font-semibold ${confidenceColor}`}>
              {insight.confidence}% confident
            </span>
            <span className="text-xs text-gray-500 dark:text-gray-500">
              {insight.timestamp.toLocaleTimeString([], {
                hour: '2-digit',
                minute: '2-digit',
              })}
            </span>
          </div>

          {/* Actions */}
          <div className="flex gap-2 mt-3">
            <button
              onClick={() => setShowDetails(!showDetails)}
              className="text-xs px-2 py-1 text-blue-600 dark:text-blue-400 hover:bg-blue-50 dark:hover:bg-blue-900/20 rounded transition-colors"
            >
              {showDetails ? 'Hide' : 'Explain'}
            </button>
            {insight.action && (
              <button
                onClick={insight.action.onClick}
                className="text-xs px-2 py-1 text-green-600 dark:text-green-400 hover:bg-green-50 dark:hover:bg-green-900/20 rounded transition-colors"
              >
                {insight.action.label}
              </button>
            )}
          </div>

          {/* Details */}
          {showDetails && (
            <div className="mt-3 pt-3 border-t border-gray-200 dark:border-gray-700">
              <p className="text-xs text-gray-600 dark:text-gray-400 leading-relaxed">
                This insight was generated by analyzing your financial data over the selected period. The high confidence score indicates this finding is based on strong statistical patterns in your receivables aging data.
              </p>
            </div>
          )}
        </div>
      </div>
    </div>
  );
}
